-- =====================================================================
-- v8: customer order tracking ("My orders"). Safe to re-run.
-- A customer can only see an order if they know BOTH its code and the phone number used.
-- Name, address and other customers' data are never returned.
-- =====================================================================
create or replace function public.track_orders(p_orders jsonb)
returns table(order_code text, status text, estimated_prep_minutes integer, total integer, items jsonb, created_at timestamptz, updated_at timestamptz, timeline jsonb)
language plpgsql stable security definer set search_path=public
as $$
begin
  if p_orders is null or jsonb_typeof(p_orders)<>'array' then raise exception 'Invalid request'; end if;
  if jsonb_array_length(p_orders)>10 then raise exception 'Too many orders requested'; end if;
  return query
    select o.order_code,o.status,o.estimated_prep_minutes,o.total,o.items,o.created_at,o.updated_at,
      coalesce((select jsonb_agg(jsonb_build_object('status',e.new_status,'at',e.created_at) order by e.created_at,e.id)
                from public.order_events e where e.order_id=o.id),'[]'::jsonb)
    from jsonb_array_elements(p_orders) q
    join public.orders o
      on o.order_code=left(coalesce(q.value->>'code',''),32)
     and right(regexp_replace(o.customer_phone,'\D','','g'),10)=right(regexp_replace(coalesce(q.value->>'phone',''),'\D','','g'),10)
     and length(regexp_replace(coalesce(q.value->>'phone',''),'\D','','g'))>=10;
end; $$;
revoke all on function public.track_orders(jsonb) from public;
grant execute on function public.track_orders(jsonb) to anon, authenticated;
