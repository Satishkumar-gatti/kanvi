-- Kanvi Cloud Kitchen production starter schema for Supabase.
-- Run in Supabase SQL Editor after creating a project. Review before production use.
create extension if not exists pgcrypto;

create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null unique,
  price integer not null check (price >= 0),
  active boolean not null default true,
  stock_qty integer not null default 0 check (stock_qty >= 0),
  low_stock_threshold integer not null default 3 check (low_stock_threshold >= 0),
  ingredient_cost numeric(10,2) not null default 0 check (ingredient_cost >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_code text not null unique,
  idempotency_key uuid not null unique,
  customer_name text not null,
  customer_phone text not null,
  area text not null,
  address text not null,
  items jsonb not null,
  total integer not null check (total >= 0),
  status text not null default 'Awaiting kitchen confirmation' check (status in ('Awaiting kitchen confirmation','Confirmed','Preparing','Ready','Delivered','Cancelled')),
  estimated_prep_minutes integer not null default 35,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.order_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  old_status text,
  new_status text not null,
  changed_by uuid,
  created_at timestamptz not null default now()
);

alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_events enable row level security;
-- No direct anonymous table access. Public ordering goes through a validated, transactional RPC.
revoke all on public.menu_items, public.orders, public.order_events from anon, authenticated;
grant select on public.menu_items to authenticated;
grant select on public.orders, public.order_events to authenticated;

create or replace function public.is_kanvi_owner()
returns boolean language sql stable security definer set search_path=public
as $$ select coalesce((auth.jwt()->'app_metadata'->>'role') = 'kanvi_owner', false); $$;

-- Owners can see/manage inventory and read all orders; customers cannot read other orders.
drop policy if exists "owner reads menu" on public.menu_items;
create policy "owner reads menu" on public.menu_items for select to authenticated using (public.is_kanvi_owner());
drop policy if exists "owner reads orders" on public.orders;
create policy "owner reads orders" on public.orders for select to authenticated using (public.is_kanvi_owner());
drop policy if exists "owner reads order events" on public.order_events;
create policy "owner reads order events" on public.order_events for select to authenticated using (public.is_kanvi_owner());

create or replace function public.create_order_request(
  p_idempotency_key uuid,
  p_customer_name text,
  p_customer_phone text,
  p_area text,
  p_address text,
  p_items jsonb
) returns jsonb language plpgsql security definer set search_path=public
as $$
declare
  existing public.orders%rowtype;
  line jsonb;
  item_name text;
  qty integer;
  item_row public.menu_items%rowtype;
  total_amount integer := 0;
  normalized_items jsonb := '[]'::jsonb;
  order_uuid uuid;
  order_code text;
  item_count integer := 0;
  prep_minutes integer;
begin
  if p_idempotency_key is null then raise exception 'Missing request key'; end if;
  select * into existing from public.orders where idempotency_key=p_idempotency_key;
  if found then return jsonb_build_object('order_id',existing.order_code,'total',existing.total,'items',existing.items,'estimated_prep_minutes',existing.estimated_prep_minutes,'was_duplicate',true); end if;
  if length(trim(coalesce(p_customer_name,''))) not between 2 and 80 then raise exception 'Enter a valid name'; end if;
  if coalesce(p_customer_phone,'') !~ '^[0-9]{10}$' then raise exception 'Enter a valid 10-digit phone number'; end if;
  if (select count(*) from public.orders where customer_phone=p_customer_phone and status='Awaiting kitchen confirmation' and created_at>now()-interval '1 hour')>=3 then raise exception 'Too many pending orders from this number. Please wait for the kitchen to confirm.'; end if;
  if length(trim(coalesce(p_area,''))) not between 2 and 100 then raise exception 'Choose a delivery area'; end if;
  if length(trim(coalesce(p_address,''))) not between 5 and 500 then raise exception 'Enter a complete address'; end if;
  if p_items is null or jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items)=0 or jsonb_array_length(p_items)>30 then raise exception 'Cart is empty or too large'; end if;
  -- One line per dish prevents ambiguous stock restoration and duplicate line-item tricks.
  if (select count(*) from jsonb_array_elements(p_items)) <>
     (select count(distinct value->>'name') from jsonb_array_elements(p_items)) then
    raise exception 'Cart contains a duplicate dish line. Please refresh and try again.';
  end if;
  -- Sort order of stock locks avoids deadlocks when concurrent orders contain the same dishes.
  for line in select value from jsonb_array_elements(p_items) order by value->>'name' loop
    item_name := trim(coalesce(line->>'name',''));
    if coalesce(line->>'quantity','') !~ '^[0-9]{1,2}$' then raise exception 'Invalid quantity'; end if;
    qty := (line->>'quantity')::integer;
    if qty < 1 or qty > 20 then raise exception 'Quantity must be between 1 and 20'; end if;
    select * into item_row from public.menu_items where name=item_name and active=true for update;
    if not found then raise exception 'A dish is unavailable: %',item_name; end if;
    if item_row.stock_qty < qty then raise exception 'Not enough stock for %. Available: %',item_name,item_row.stock_qty; end if;
    update public.menu_items set stock_qty=stock_qty-qty,updated_at=now() where id=item_row.id;
    total_amount := total_amount + least(coalesce(item_row.offer_price,item_row.price),item_row.price)*qty;
    item_count := item_count + qty;
    normalized_items := normalized_items || jsonb_build_array(jsonb_build_object('name',item_name,'quantity',qty,'unit_price',least(coalesce(item_row.offer_price,item_row.price),item_row.price),'line_total',least(coalesce(item_row.offer_price,item_row.price),item_row.price)*qty));
  end loop;
  prep_minutes := least(120,greatest(25,25+item_count*5 + (select count(*)*3 from public.orders where status in ('Awaiting kitchen confirmation','Confirmed','Preparing'))));
  order_uuid := gen_random_uuid();
  order_code := 'KNV-' || upper(substr(replace(order_uuid::text,'-',''),1,8));
  insert into public.orders(id,order_code,idempotency_key,customer_name,customer_phone,area,address,items,total,estimated_prep_minutes)
  values(order_uuid,order_code,p_idempotency_key,trim(p_customer_name),p_customer_phone,trim(p_area),trim(p_address),normalized_items,total_amount,prep_minutes);
  insert into public.order_events(order_id,new_status) values(order_uuid,'Awaiting kitchen confirmation');
  return jsonb_build_object('order_id',order_code,'total',total_amount,'items',normalized_items,'estimated_prep_minutes',prep_minutes,'was_duplicate',false);
exception when unique_violation then
  select * into existing from public.orders where idempotency_key=p_idempotency_key;
  if found then return jsonb_build_object('order_id',existing.order_code,'total',existing.total,'items',existing.items,'estimated_prep_minutes',existing.estimated_prep_minutes,'was_duplicate',true); end if;
  raise;
end; $$;
revoke all on function public.create_order_request(uuid,text,text,text,text,jsonb) from public;
grant execute on function public.create_order_request(uuid,text,text,text,text,jsonb) to anon, authenticated;

create or replace function public.owner_update_order_status(p_order_code text,p_new_status text)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare o public.orders%rowtype;
begin
 if not public.is_kanvi_owner() then raise exception 'Owner access required'; end if;
 if p_new_status not in ('Awaiting kitchen confirmation','Confirmed','Preparing','Ready','Delivered','Cancelled') then raise exception 'Invalid status'; end if;
 select * into o from public.orders where order_code=p_order_code for update;
 if not found then raise exception 'Order not found'; end if;
 if o.status=p_new_status then
   return jsonb_build_object('order_id',o.order_code,'status',o.status,'unchanged',true);
 end if;
 if not (
   (o.status='Awaiting kitchen confirmation' and p_new_status in ('Confirmed','Cancelled')) or
   (o.status='Confirmed' and p_new_status in ('Preparing','Cancelled')) or
   (o.status='Preparing' and p_new_status='Ready') or
   (o.status='Ready' and p_new_status='Delivered')
 ) then raise exception 'Invalid order status transition: % to %',o.status,p_new_status; end if;
 if o.status<>'Cancelled' and p_new_status='Cancelled' then
   -- Aggregate by dish name so every reserved serving is restored exactly once.
   update public.menu_items m set stock_qty=m.stock_qty+x.qty,updated_at=now()
   from (select value->>'name' as name,sum((value->>'quantity')::int)::int as qty
         from jsonb_array_elements(o.items) group by value->>'name') x
   where m.name=x.name;
 end if;
 update public.orders set status=p_new_status,updated_at=now() where id=o.id;
 insert into public.order_events(order_id,old_status,new_status,changed_by) values(o.id,o.status,p_new_status,auth.uid());
 return jsonb_build_object('order_id',o.order_code,'status',p_new_status);
end; $$;
revoke all on function public.owner_update_order_status(text,text) from public;
grant execute on function public.owner_update_order_status(text,text) to authenticated;

