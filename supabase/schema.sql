-- Owner: banner + Swiggy / Zomato / Instagram / Google-review links.
create or replace function public.owner_set_settings(p jsonb)
returns jsonb language plpgsql security definer set search_path=public
as $$ declare k text; v text;
begin
  if not public.is_kanvi_owner() then raise exception 'Owner access required'; end if;
  foreach k in array array['swiggy','zomato','instagram','google_review'] loop
    v:=trim(coalesce(p->>k,''));
    if v<>'' and (length(v)>500 or v !~* '^https?://[^ ]+$') then raise exception 'The % link must start with https://',k; end if;
  end loop;
  if length(coalesce(p->>'banner',''))>200 then raise exception 'Banner is too long (max 200 characters)'; end if;
  insert into public.shop_settings(id,banner,swiggy,zomato,instagram,google_review,updated_at)
  values(1,trim(coalesce(p->>'banner','')),trim(coalesce(p->>'swiggy','')),trim(coalesce(p->>'zomato','')),trim(coalesce(p->>'instagram','')),trim(coalesce(p->>'google_review','')),now())
  on conflict(id) do update set banner=excluded.banner,swiggy=excluded.swiggy,zomato=excluded.zomato,instagram=excluded.instagram,google_review=excluded.google_review,updated_at=now();
  return public.get_shop_settings();
end; $$;
revoke all on function public.owner_set_settings(jsonb) from public;
revoke execute on function public.owner_set_settings(jsonb) from anon;
grant execute on function public.owner_set_settings(jsonb) to authenticated;

