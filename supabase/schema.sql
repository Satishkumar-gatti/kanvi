-- Owner: add a new dish or edit an existing one (price, offer, image, veg, stock ...).
create or replace function public.owner_upsert_item(p jsonb)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare m public.menu_items%rowtype; v_old text; v_name text; v_cat text; v_price int; v_offer int; v_img text; v_stock int; v_id bigint;
begin
  if not public.is_kanvi_owner() then raise exception 'Owner access required'; end if;
  v_name:=trim(coalesce(p->>'name',''));
  if length(v_name) not between 2 and 80 then raise exception 'Dish name must be 2-80 characters'; end if;
  v_cat:=coalesce(p->>'category','');
  if v_cat not in ('Biryani','Starters','Curries') then raise exception 'Choose Biryani, Starters or Curries'; end if;
  if coalesce(p->>'price','') !~ '^[0-9]{1,4}$' or (p->>'price')::int>5000 then raise exception 'Enter a price between 0 and 5000'; end if;
  v_price:=(p->>'price')::int;
  if coalesce(p->>'offer_price','')<>'' then
    if p->>'offer_price' !~ '^[0-9]{1,4}$' then raise exception 'Enter a valid offer price'; end if;
    v_offer:=(p->>'offer_price')::int;
    if v_offer>=v_price then raise exception 'Offer price must be lower than the normal price'; end if;
  end if;
  v_img:=trim(coalesce(p->>'img',''));
  if v_img<>'' and (length(v_img)>500 or v_img like '%..%' or v_img !~ '^(https://[^ ]+|[A-Za-z0-9_./-]+)$') then raise exception 'Invalid image'; end if;
  if coalesce(p->>'stock_qty','')<>'' then
    if p->>'stock_qty' !~ '^[0-9]{1,5}$' or (p->>'stock_qty')::int>10000 then raise exception 'Stock must be between 0 and 10000'; end if;
    v_stock:=(p->>'stock_qty')::int;
  end if;
  if coalesce(p->>'id','')='' then
    insert into public.menu_items(name,category,price,offer_price,veg,special,img,description,stock_qty,active,sort_order)
    values(v_name,v_cat,v_price,v_offer,coalesce((p->>'veg')::boolean,true),coalesce((p->>'special')::boolean,false),v_img,
      left(trim(coalesce(p->>'description','')),300),coalesce(v_stock,0),coalesce((p->>'active')::boolean,true),
      coalesce((select max(sort_order) from public.menu_items),0)+1)
    returning * into m;
  else
    v_id:=(p->>'id')::bigint;
    select name into v_old from public.menu_items where id=v_id for update;
    if not found then raise exception 'Menu item not found'; end if;
    if v_old<>v_name and exists(select 1 from public.orders o where o.status in ('Awaiting kitchen confirmation','Confirmed','Preparing') and o.items @> jsonb_build_array(jsonb_build_object('name',v_old))) then
      raise exception 'Finish or cancel the open orders for "%" before renaming it',v_old;
    end if;
    update public.menu_items set name=v_name,category=v_cat,price=v_price,offer_price=v_offer,
      veg=coalesce((p->>'veg')::boolean,veg),special=coalesce((p->>'special')::boolean,special),img=v_img,
      description=left(trim(coalesce(p->>'description','')),300),stock_qty=coalesce(v_stock,stock_qty),
      active=coalesce((p->>'active')::boolean,active),updated_at=now()
    where id=v_id returning * into m;
  end if;
  return to_jsonb(m);
exception when unique_violation then raise exception 'A dish with this name already exists';
end; $$;
revoke all on function public.owner_upsert_item(jsonb) from public;
revoke execute on function public.owner_upsert_item(jsonb) from anon;
grant execute on function public.owner_upsert_item(jsonb) to authenticated;

create or replace function public.owner_delete_item(p_item_id bigint)
returns jsonb language plpgsql security definer set search_path=public
as $$ declare v_name text;
begin
  if not public.is_kanvi_owner() then raise exception 'Owner access required'; end if;
  select name into v_name from public.menu_items where id=p_item_id for update;
  if not found then raise exception 'Menu item not found'; end if;
  if exists(select 1 from public.orders o where o.status in ('Awaiting kitchen confirmation','Confirmed','Preparing') and o.items @> jsonb_build_array(jsonb_build_object('name',v_name))) then
    raise exception 'Finish or cancel the open orders for "%" before deleting it (or mark it Sold out instead)',v_name;
  end if;
  delete from public.menu_items where id=p_item_id;
  return jsonb_build_object('deleted',p_item_id);
end; $$;
