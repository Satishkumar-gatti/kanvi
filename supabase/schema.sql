returns jsonb language plpgsql security definer set search_path=public
as $$ declare m public.menu_items%rowtype;
begin
 if not public.is_kanvi_owner() then raise exception 'Owner access required'; end if;
 if p_stock_qty<0 or p_stock_qty>10000 then raise exception 'Stock must be between 0 and 10000'; end if;
 update public.menu_items set stock_qty=p_stock_qty,active=p_active,updated_at=now() where id=p_item_id returning * into m;
 if not found then raise exception 'Menu item not found'; end if;
 return jsonb_build_object('id',m.id,'name',m.name,'stock_qty',m.stock_qty,'active',m.active);
end; $$;
