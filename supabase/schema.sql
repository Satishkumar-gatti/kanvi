create or replace function public.owner_set_price(p_item_id bigint,p_price integer)
returns jsonb language plpgsql security definer set search_path=public
as $$ declare m public.menu_items%rowtype;
begin
  if not public.is_kanvi_owner() then raise exception 'Owner access required'; end if;
  if p_price<0 or p_price>5000 then raise exception 'Price must be between 0 and 5000'; end if;
  update public.menu_items set price=p_price,offer_price=case when offer_price<p_price then offer_price end,updated_at=now() where id=p_item_id returning * into m;
  if not found then raise exception 'Menu item not found'; end if;
  return jsonb_build_object('id',m.id,'name',m.name,'price',m.price);
end; $$;
revoke all on function public.owner_set_price(bigint,integer) from public;
grant execute on function public.owner_set_price(bigint,integer) to authenticated;

